from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from collections import Counter
from pathlib import Path
from typing import Any

if __package__ in (None, ""):
    # data_cleaning_v1 包与本脚本同处 scripts/ 目录，将 scripts/ 加入 sys.path。
    sys.path.insert(0, str(Path(__file__).resolve().parent))

from data_cleaning_v1.submission_schema import (
    COVERAGE_COLUMNS,
    EVIDENCE_COLUMNS,
    RELATIONS_COLUMNS,
    RESOURCE_COLUMNS,
    TEAMS_COLUMNS,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Validate one imported data.json and report passed and failed checks."
    )
    parser.add_argument(
        "--data",
        type=Path,
        required=True,
        help="Path to data.json generated by import_snapshot.py.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Directory for validation_report.json and passed/failed CSV files.",
    )
    return parser.parse_args()


def read_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def write_csv(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    columns = ["check_id", "status", "message", "details"]
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def check(
    checks: list[dict[str, Any]],
    check_id: str,
    passed: bool,
    message: str,
    details: str = "",
) -> None:
    checks.append(
        {
            "check_id": check_id,
            "status": "通过" if passed else "未通过",
            "message": message,
            "details": details,
        }
    )


def unique(values: list[str]) -> bool:
    return len(values) == len(set(values))


def main() -> int:
    args = parse_args()
    data_path = args.data.resolve()
    output = args.output.resolve()
    if not data_path.is_file():
        raise FileNotFoundError(f"data.json does not exist: {data_path}")
    data = read_json(data_path)
    checks: list[dict[str, Any]] = []

    required_sections = {
        "metadata",
        "taxonomy",
        "teams",
        "evidence",
        "relations",
        "coverage",
        "resources",
        "tables",
    }
    missing_sections = sorted(required_sections - set(data))
    check(
        checks,
        "structure.sections",
        not missing_sections,
        "data.json包含必要数据区段。",
        ",".join(missing_sections),
    )

    tables = data.get("tables", {})
    expected_columns = {
        "teams": TEAMS_COLUMNS,
        "evidence": EVIDENCE_COLUMNS,
        "relations": RELATIONS_COLUMNS,
        "coverage": COVERAGE_COLUMNS,
    }
    for table_name, columns in expected_columns.items():
        actual = list(tables.get(table_name, [{}])[0].keys()) if tables.get(table_name) else columns
        check(
            checks,
            f"schema.{table_name}",
            actual == columns,
            f"{table_name}.csv列名与原始提供文件一致。",
            f"expected={columns}; actual={actual}",
        )

    teams = data.get("teams", [])
    evidence = data.get("evidence", [])
    relations = data.get("relations", [])
    coverage = data.get("coverage", [])
    resources = data.get("resources", [])
    missing_items = data.get("missing_items", [])
    taxonomy = data.get("taxonomy", [])

    team_ids = [row.get("team_id", "") for row in teams]
    evidence_ids = [row.get("evidence_id", "") for row in evidence]
    check(
        checks,
        "ids.teams",
        unique(team_ids) and all(team_ids),
        "团队ID非空且不重复。",
        f"count={len(team_ids)}",
    )
    check(
        checks,
        "ids.evidence",
        unique(evidence_ids) and all(evidence_ids),
        "证据ID非空且不重复。",
        f"count={len(evidence_ids)}",
    )
    relation_keys = [
        (row.get("team_id", ""), row.get("evidence_id", ""), row.get("relation_type", ""))
        for row in relations
    ]
    check(
        checks,
        "ids.relations",
        unique(["|".join(key) for key in relation_keys]),
        "关系复合ID不重复。",
        f"count={len(relation_keys)}",
    )

    required_evidence_fields = (
        "evidence_id",
        "title",
        "source_url",
        "source_name",
        "captured_at",
        "raw_path",
        "verification_status",
    )
    missing_sources = [
        row.get("evidence_id", "")
        for row in data.get("tables", {}).get("evidence", [])
        if any(not row.get(field) for field in required_evidence_fields)
    ]
    check(
        checks,
        "sources.required",
        not missing_sources,
        "证据记录包含必填来源、采集时间和原文定位。",
        f"missing_count={len(missing_sources)}; sample={missing_sources[:10]}",
    )

    news_mapping_errors: list[str] = []
    for row in evidence:
        if row.get("evidence_type") != "news_fetch":
            continue
        raw = row.get("raw_record", {})
        expected = {
            "evidence_title": raw.get("title"),
            "source_url": raw.get("link"),
            "published_at": raw.get("published"),
            "source_name": raw.get("source"),
            "summary": raw.get("summary"),
            "raw_text": raw.get("content"),
        }
        for field, raw_value in expected.items():
            if row.get(field, "") != ("" if raw_value is None else str(raw_value)):
                news_mapping_errors.append(
                    f"{row.get('evidence_id', '')}:{field}"
                )
        source_key = str(row.get("source_record_key", ""))
        if not re.search(r"^fetch-[^#]+#\d+$", source_key):
            news_mapping_errors.append(
                f"{row.get('evidence_id', '')}:source_record_key"
            )
    check(
        checks,
        "mapping.news_fields",
        not news_mapping_errors,
        "新闻证据字段与原始entries字段映射一致。",
        f"error_count={len(news_mapping_errors)}; sample={news_mapping_errors[:10]}",
    )

    team_set = set(team_ids)
    evidence_set = set(evidence_ids)
    orphan_relations = [
        row
        for row in relations
        if row.get("team_id") not in team_set or row.get("evidence_id") not in evidence_set
    ]
    check(
        checks,
        "relations.orphans",
        not orphan_relations,
        "关系中的团队ID和证据ID均可在主表中找到。",
        f"orphan_count={len(orphan_relations)}",
    )

    domains_by_name: dict[str, set[str]] = {}
    for row in taxonomy:
        domains_by_name.setdefault(row.get("domain_name", ""), set()).add(
            row.get("subdomain_name", "")
        )
    allowed_domains = {name for name in domains_by_name if name}
    invalid_domains = [
        row.get("team_id", "")
        for row in teams
        if row.get("mapped_domain_name") not in allowed_domains
    ]
    invalid_subdomains = [
        row.get("team_id", "")
        for row in teams
        if row.get("mapped_subdomain_name")
        and row.get("mapped_subdomain_name") not in domains_by_name.get(
            row.get("mapped_domain_name", ""), set()
        )
    ]
    check(
        checks,
        "taxonomy.domain_enum",
        not invalid_domains,
        "团队领域均属于输入快照的领域枚举。",
        f"invalid_count={len(invalid_domains)}",
    )
    check(
        checks,
        "taxonomy.subdomain_enum",
        not invalid_subdomains,
        "团队子领域均属于对应领域枚举。",
        f"invalid_count={len(invalid_subdomains)}",
    )

    def coverage_domain(row: dict[str, Any]) -> str:
        return row.get("domain_name") or row.get("domain", "")

    coverage_domain_counts = Counter(coverage_domain(row) for row in coverage)
    team_domain_counts = Counter(row.get("mapped_domain_name", "") for row in teams)
    coverage_count_match = all(
        int(row.get("candidate_count", 0)) == team_domain_counts.get(coverage_domain(row), 0)
        for row in coverage
    )
    check(
        checks,
        "stats.coverage_candidates",
        coverage_count_match
        and sum(int(row.get("candidate_count", 0)) for row in coverage) == len(teams),
        "覆盖表候选数与团队清单统计一致。",
        f"team_count={len(teams)}; coverage_count={sum(int(row.get('candidate_count', 0)) for row in coverage)}",
    )
    coverage_status_match = all(
        int(row.get("verified_count", 0))
        + int(row.get("pending_count", 0))
        + int(row.get("rejected_count", 0))
        == int(row.get("candidate_count", 0))
        for row in coverage
    )
    check(
        checks,
        "stats.coverage_statuses",
        coverage_status_match,
        "覆盖表各状态计数之和等于候选数。",
    )
    check(
        checks,
        "stats.coverage_domains",
        len(coverage_domain_counts) == len(allowed_domains)
        and not (coverage_domain_counts - Counter({domain: 1 for domain in allowed_domains})),
        "覆盖表覆盖全部领域且每个领域一行。",
        f"taxonomy_domains={len(allowed_domains)}; coverage_rows={len(coverage)}",
    )

    resource_fields_ok = all(
        all(row.get(field) not in (None, "") for field in RESOURCE_COLUMNS[:5])
        for row in resources
    )
    check(
        checks,
        "resources.required",
        bool(resources) and resource_fields_ok,
        "资源需求表包含资源ID、类型、名称、状态和优先级。",
        f"resource_count={len(resources)}",
    )

    missing_keys = {
        (row.get("record_type", ""), row.get("record_id", ""), row.get("field", ""))
        for row in missing_items
    }
    unmarked_missing: list[str] = []
    for row in teams:
        team_id = row.get("team_id", "")
        for field in ("mapped_domain_name", "mapped_subdomain_name"):
            missing_field = "domain" if field == "mapped_domain_name" else "subdomain"
            if not row.get(field) and ("team", team_id, missing_field) not in missing_keys:
                unmarked_missing.append(f"{team_id}:{field}")
        for item in row.get("pending_materials", []):
            if ("team", team_id, item) not in missing_keys:
                unmarked_missing.append(f"{team_id}:{item}")
    check(
        checks,
        "missing.marked",
        not unmarked_missing,
        "缺失字段和待补材料已在缺项清单中标记。",
        f"unmarked_count={len(unmarked_missing)}; sample={unmarked_missing[:10]}",
    )

    metadata = data.get("metadata", {})
    check(
        checks,
        "metadata.batch",
        bool(metadata.get("snapshot_date"))
        and bool(metadata.get("imported_at"))
        and bool(metadata.get("import_batch")),
        "输入快照日期、导入时间和导入批次均有记录。",
    )
    check(
        checks,
        "metadata.raw_preserved",
        all("raw_record" in row for row in evidence)
        and all("raw_record" in row for row in teams),
        "团队和证据均保留原始记录。",
    )
    score_or_tags_lost = [
        row.get("evidence_id", "")
        for row in evidence
        if row.get("evidence_type") == "news_fetch"
        and (
            "score" not in row.get("raw_record", {})
            or "tags" not in row.get("raw_record", {})
        )
    ]
    check(
        checks,
        "metadata.score_tags",
        not score_or_tags_lost,
        "原始新闻记录中的score和tags仍保留在raw_record中。",
        f"missing_count={len(score_or_tags_lost)}",
    )

    output.mkdir(parents=True, exist_ok=True)
    passed = [row for row in checks if row["status"] == "通过"]
    failed = [row for row in checks if row["status"] == "未通过"]
    write_csv(output / "validation_passed.csv", passed)
    write_csv(output / "validation_failed.csv", failed)
    report = {
        "data": str(data_path),
        "passed": len(passed),
        "failed": len(failed),
        "status": "通过" if not failed else "未通过",
        "checks": checks,
    }
    with (output / "validation_report.json").open("w", encoding="utf-8") as handle:
        json.dump(report, handle, ensure_ascii=False, indent=2)
        handle.write("\n")

    print(f"Validation: {report['status']}")
    print(f"Passed: {len(passed)}")
    print(f"Failed: {len(failed)}")
    for row in failed:
        print(f"[未通过] {row['check_id']}: {row['message']} {row['details']}")
    return 0 if not failed else 1


if __name__ == "__main__":
    raise SystemExit(main())
