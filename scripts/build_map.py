def write_team_cards(output: Path, data: dict[str, Any]) -> None:
    cards = output / "team_cards"
    cards.mkdir(parents=True, exist_ok=True)
    date = data["metadata"].get("snapshot_date", "")
    teams = data.get("teams", [])
    links = []
    for team in teams:
        team_id = str(team.get("team_id", ""))
        filename = f"team_{slug(team_id)}.html"
        (cards / filename).write_text(team_card_html(team, date), encoding="utf-8")
        links.append(
            f'<li><a href="{html.escape(filename)}">'
            f'{html.escape(str(team.get("team_name", "")))}'
            f'</a>（{html.escape(str(team.get("mapped_domain_name", "")))}）</li>'
        )
    (cards / "index.html").write_text(
        "<!doctype html><html lang='zh-CN'><meta charset='utf-8'>"
        "<title>团队卡片</title><body><h1>团队卡片</h1><ul>"
        + "".join(links)
        + "</ul></body></html>",
        encoding="utf-8",
    )


def write_preview(output: Path, data: dict[str, Any]) -> None:
    tables = data.get("tables", {})
    teams = tables.get("teams", [])
    coverage = tables.get("coverage", [])
    domains = list(DOMAIN_NAMES)
    embedded = json.dumps(
        {"teams": teams, "coverage": coverage},
        ensure_ascii=False,
        separators=(",", ":"),
    ).replace("<", "\\u003c")
    options = "".join(
        f"<option value='{html.escape(domain)}'>{html.escape(domain)}</option>"
        for domain in domains
    )
    date = html.escape(str(data["metadata"].get("snapshot_date", "")))
    html_text = f"""<!doctype html>
<html lang="zh-CN">
<head><meta charset="utf-8"><title>国内战略力量图谱本地预览</title>
<style>
body {{ font-family: Arial, "Microsoft YaHei", sans-serif; margin: 24px; color: #172033; }}
header {{ border-bottom: 1px solid #d6deea; margin-bottom: 18px; }}
select {{ padding: 7px; min-width: 220px; }}
table {{ border-collapse: collapse; width: 100%; margin-top: 18px; }}
th, td {{ border: 1px solid #d6deea; padding: 7px 9px; text-align: left; }}
th {{ background: #f4f7fb; }}
.muted {{ color: #667085; }}
a {{ color: #245f9e; }}
</style></head>
<body>
<header><h1>国内战略力量图谱本地预览</h1>
<p class="muted">输入快照日期：{date}。统计全部来自同一份 data.json。</p>
<p><a href="total_graph_{date.replace('-', '')}.svg">总图</a> |
<a href="team_cards/index.html">团队卡片</a></p></header>
<label>领域：
<select id="domain"><option value="">全部</option>{options}</select></label>
<table><thead><tr><th>团队</th><th>机构</th><th>领域</th><th>子领域</th><th>方向</th><th>状态</th></tr></thead>
<tbody id="rows"></tbody></table>
<script>
const DATA = {embedded};
const select = document.getElementById("domain");
const rows = document.getElementById("rows");
function render() {{
  const domain = select.value;
  rows.innerHTML = DATA.teams.filter(t => !domain || t.domain === domain).map(t => {{
    const href = "team_cards/team_" + t.team_id + ".html";
    return `<tr><td><a href="${{href}}">${{t.team_name || ""}}</a></td>
      <td>${{t.institution || ""}}</td><td>${{t.domain || ""}}</td>
      <td>${{t.subdomain || ""}}</td><td>${{t.direction || ""}}</td>
      <td>${{t.verification_status || ""}}</td></tr>`;
  }}).join("");
}}
select.addEventListener("change", render); render();
</script>
</body></html>"""
    (output / "index.html").write_text(html_text, encoding="utf-8")


