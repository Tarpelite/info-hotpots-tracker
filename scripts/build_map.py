def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build maps, team cards, coverage, and a local HTML preview from one data.json."
    )
    parser.add_argument(
        "--data",
        type=Path,
        required=True,
        help="Path to data.json generated by import_snapshot.py.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Directory for map SVGs, team cards, tables, and local preview.",
    )
    return parser.parse_args()


def load_data(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def write_csv(path: Path, rows: list[dict[str, Any]], columns: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns, lineterminator="\n")
        writer.writeheader()
        writer.writerows({column: row.get(column, "") for column in columns} for row in rows)


def slug(value: str) -> str:
    value = re.sub(r"[^\w\u4e00-\u9fff-]+", "-", value, flags=re.UNICODE).strip("-")
    return value or "item"


def code_for_domain(domain: str, domains: list[str]) -> str:
    return f"{domains.index(domain) + 1:02d}-{slug(domain)}"


def svg_text(x: int, y: int, text: str, size: int = 18, weight: str = "400") -> str:
    return (
        f'<text x="{x}" y="{y}" font-family="Microsoft YaHei, Arial, sans-serif" '
        f'font-size="{size}" font-weight="{weight}" fill="#172033">'
        f"{html.escape(str(text))}</text>"
    )


def svg_box(
    x: int,
    y: int,
    width: int,
    height: int,
    label: str,
    fill: str = "#f4f7fb",
    stroke: str = "#7891b7",
    size: int = 18,
) -> str:
    return (
        f'<rect x="{x}" y="{y}" width="{width}" height="{height}" rx="6" '
        f'fill="{fill}" stroke="{stroke}" stroke-width="1.5"/>'
        + svg_text(x + 14, y + 28, label, size=size)
    )


def write_total_svg(output: Path, data: dict[str, Any]) -> None:
    date = data["metadata"].get("snapshot_date", "")
    coverage = data.get("coverage", [])
    width = 1600
    height = 720
    pieces = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" fill="#ffffff"/>',
        svg_text(70, 60, f"国内战略力量图谱总图（快照：{date}）", 28, "700"),
        svg_text(70, 92, "候选团队总数来自同一份 data.json，不代表已核实数量。", 16),
    ]
    center_x = width // 2
    center_y = 150
    pieces.append(svg_box(center_x - 190, center_y, 380, 72, "国内战略力量候选图谱", "#e8f0fb", "#376da5", 22))
    start_x = 90
    start_y = 300
    box_width = 440
    box_height = 86
    gap_x = 80
    gap_y = 52
    for index, row in enumerate(coverage):
        col = index % 3
        line = index // 3
        x = start_x + col * (box_width + gap_x)
        y = start_y + line * (box_height + gap_y)
        count = row.get("candidate_count", 0)
        label = f"{row.get('domain', '')}：{count} 个候选团队"
        pieces.append(svg_box(x, y, box_width, box_height, label))
        pieces.append(
            f'<line x1="{center_x}" y1="{center_y + 72}" x2="{x + box_width // 2}" '
            f'y2="{y}" stroke="#9aacc6" stroke-width="1.5"/>'
        )
    pieces.append("</svg>")
    output.write_text("\n".join(pieces), encoding="utf-8")


def write_domain_svg(
    output: Path,
    domain: str,
    data: dict[str, Any],
    domain_index: int,
) -> None:
    date = data["metadata"].get("snapshot_date", "")
    teams = [
        team
        for team in data.get("teams", [])
        if team.get("mapped_domain_name") == domain
    ]
    subdomains: dict[str, list[dict[str, Any]]] = {}
    for team in teams:
        subdomains.setdefault(team.get("mapped_subdomain_name") or "待核实", []).append(team)

    width = 1900
    top = 145
    row_height = 64
    header_height = 90
    height = max(560, top + header_height + sum(max(1, len(items)) * row_height for items in subdomains.values()) + 80)
    pieces = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
        f'viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" fill="#ffffff"/>',
        svg_text(55, 58, f"{domain}（快照：{date}）", 28, "700"),
        svg_text(55, 92, f"候选团队 {len(teams)} 个；项目核实状态均按当前数据标记。", 16),
    ]
    left_x = 60
    sub_width = 420
    team_x = 560
    team_width = 1230
    y = top
    for subdomain, subteams in sorted(subdomains.items()):
        block_height = max(1, len(subteams)) * row_height
        pieces.append(svg_box(left_x, y, sub_width, block_height, f"{subdomain}：{len(subteams)}", "#eef5f2", "#63927d"))
        for index, team in enumerate(sorted(subteams, key=lambda item: item.get("team_name", ""))):
            team_y = y + index * row_height
            label = (
                f"{team.get('team_name', '')} | "
                f"{team.get('mapped_research_direction', '')[: eighty_chars()]}"
            )
            pieces.append(svg_box(team_x, team_y, team_width, 46, label, "#f8f9fb", "#a7b4c7", 15))
            pieces.append(
                f'<line x1="{left_x + sub_width}" y1="{y + block_height // 2}" '
                f'x2="{team_x}" y2="{team_y + 23}" stroke="#9aacc6" stroke-width="1"/>'
            )
        y += block_height + 24
    pieces.append("</svg>")
    output.write_text("\n".join(pieces), encoding="utf-8")


def eighty_chars() -> int:
    return 80


